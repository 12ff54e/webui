// Run with an unpacked official npm package. Consumers need no build step.
import {readFile, writeFile, mkdir, cp} from 'node:fs/promises';
import {resolve, join} from 'node:path';

const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/vendor-katex.mjs <unpacked-katex-package>');
const root = resolve(source);
const version = '0.19.1';
const info = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
if (info.name !== 'katex' || info.version !== version) throw new Error(`Expected katex ${version}.`);

// This pinned stylesheet contains only flat style rules and @font-face blocks.
// Reject new rule types on upgrades instead of emitting unscoped selectors.
const css = (await readFile(join(root, 'dist/katex.css'), 'utf8')).replace(/\/\*[\s\S]*?\*\//g, '').trim();
let offset = 0;
const rules = [];
for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (match.index !== offset) throw new Error('Unexpected nested KaTeX CSS rule.');
    offset = match.index + match[0].length;
    const selector = match[1].trim();
    let body = match[2].trim().replace(/[ \t]+$/gm, '');
    if (selector === '@font-face') {
        body = body.replace(/src:[^;]+;/, declaration => {
            const font = declaration.match(/url\((fonts\/[^)]+\.woff2)\)/);
            if (!font) throw new Error('Expected a local WOFF2 font.');
            return `src: url(${font[1]}) format("woff2");`;
        });
        rules.push(`@font-face {\n  ${body}\n}`);
    } else {
        const scoped = selector.split(',').map(part => {
            part = part.trim();
            if (part === 'body') return '.wui';
            if (!part.startsWith('.katex')) throw new Error(`Unexpected KaTeX selector: ${part}`);
            return `.wui ${part}`;
        });
        rules.push(`${scoped.join(',\n')} {\n${body ? `  ${body}\n` : ''}}`);
    }
}
if (offset !== css.length) throw new Error('Unparsed KaTeX CSS.');
const output = new URL('../vendor/katex/', import.meta.url);
await mkdir(new URL('fonts/', output), {recursive: true});
await cp(join(root, 'dist/katex.mjs'), new URL('katex.mjs', output));
await cp(join(root, 'LICENSE'), new URL('LICENSE', output));
for (const [, name] of css.matchAll(/url\(fonts\/([^)]*\.woff2)\)/g))
    await cp(join(root, 'dist/fonts', name), new URL(`fonts/${name}`, output));
await writeFile(new URL('katex.css', output), `/* KaTeX ${version}; generated by scripts/vendor-katex.mjs. */\n${rules.join('\n')}\n`);
console.log(`Bundled KaTeX ${version} with scoped CSS and local WOFF2 fonts.`);
